#!/usr/bin/env bash
# Usage: docker compose exec -T mssql bash /tests/permissions_mssql.sh
# Each test: role | command | expected result (OK = executed, DENIED = no privileges, ERROR = other error, e.g. a business rule)
# The command runs in a transaction rolled back at the end (a trigger violating a rule rolls the transaction back itself).
run() {
  local user=$1 pw=$2 expect=$3 sql=$4
  out=$(/opt/mssql-tools18/bin/sqlcmd -C -S localhost -U "$user" -P "$pw" -d noir -I -h -1 -Q "SET NOCOUNT ON; BEGIN TRAN; $sql; IF @@TRANCOUNT > 0 ROLLBACK;" 2>&1)
  if echo "$out" | grep -qi "permission was denied"; then got=DENIED; elif echo "$out" | grep -q "^Msg "; then got=ERROR; else got=OK; fi
  [[ $got == "$expect" ]] && res=PASS || res=FAIL
  printf '%-4s %-15s expect=%-6s got=%-6s | %s\n' "$res" "$user" "$expect" "$got" "$sql"
}
